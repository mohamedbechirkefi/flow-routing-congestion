"""Export the sandbox networks and the engine fixture for the M5 demo page.

Writes two files:

* ``demo/public/data/sandbox.json``: the Braess network and ten 4 by 4 grid-v1 networks
  generated by ``flow.generators.make_grid`` on the EXPLORATORY seeds 9000-9009 (never the
  confirmatory seeds 1000-1099 or 2000-2099), with their free-flow reference demand
  ``D_ref``. These are network definitions, not results.
* ``demo/tests/fixtures/sandbox_fixture.json``: solutions computed by the Python engine
  (free-flow loading, gradient projection for UE and SO, MIX(c)) for a few sandbox cases.
  ``demo/tests/engine.test.mjs`` checks the browser port in ``demo/site/engine.js``
  against these values within a stated tolerance. Neither file is a research result.

Deterministic: sorted keys, no timestamps. Compute: a few seconds on one core.

Usage: .venv/bin/python scripts/export_demo_sandbox.py [--check]
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

from flow.assignment import free_flow, gradient_projection, mixed_compliance
from flow.generators import braess_demand, braess_network, make_grid, reference_demand_ff

ROOT = Path(__file__).resolve().parents[1]
OUT_NETWORKS = ROOT / "demo" / "public" / "data" / "sandbox.json"
OUT_FIXTURE = ROOT / "demo" / "tests" / "fixtures" / "sandbox_fixture.json"

SEEDS = list(range(9000, 9010))  # exploratory seeds; disjoint from every confirmatory seed
GRID_N = 4
TOL = 1e-6
MAX_ITER = 20_000


def net_dict(net) -> dict:
    return {
        "n_nodes": int(net.n_nodes),
        "tail": [int(v) for v in net.tail],
        "head": [int(v) for v in net.head],
        "A": [float(v) for v in net.A],
        "B": [float(v) for v in net.B],
        "P": [float(v) for v in net.P],
        "capacity": None if net.capacity is None else [float(v) for v in net.capacity],
        "link_names": None if net.link_names is None else list(net.link_names),
    }


def networks() -> dict:
    grids = []
    for seed in SEEDS:
        inst = make_grid(GRID_N, seed)
        grids.append({
            "seed": seed,
            "n": GRID_N,
            "generator_version": inst.generator_version,
            "network": net_dict(inst.network),
            "od": [[int(o), int(d)] for o, d in inst.od],
            "weights": [float(w) for w in inst.weights],
            "d_ref": float(reference_demand_ff(inst)),
        })
    return {
        "schema": "flow-demo-sandbox",
        "schema_version": "1.0.0",
        "label": "sandbox inputs (network definitions, not results)",
        "note": "Grid networks are generated by grid-v1 (flow.generators.make_grid) on exploratory seeds 9000-9009; they are not the confirmatory instances.",
        "solver": {"algorithm": "gradient-projection", "tol": TOL, "max_iter": MAX_ITER},
        "braess": {"with_e": net_dict(braess_network(True)), "without_e": net_dict(braess_network(False)), "origin": 0, "destination": 3},
        "grids": grids,
    }


def summary(res, net) -> dict:
    x = res.link_flow
    return {
        "tstt": float(net.total_travel_time(x)),
        "link_flow": [float(v) for v in x],
        "iterations": int(res.iterations),
        "converged": bool(res.converged),
        "rel_gap": None if res.arm == "FF" else float(res.rel_gap),
    }


def solve_all(net, dem, mix_c=None) -> dict:
    out = {
        "FF": summary(free_flow(net, dem), net),
        "UE": summary(gradient_projection(net, dem, "ue", tol=TOL, max_iter=MAX_ITER), net),
    }
    so = gradient_projection(net, dem, "so", tol=TOL, max_iter=MAX_ITER)
    out["SO"] = summary(so, net)
    if mix_c is not None:
        mix = mixed_compliance(net, dem, mix_c, so_result=so, tol=TOL, max_iter=MAX_ITER, algorithm="gradient-projection")
        out[f"MIX({mix_c:g})"] = summary(mix, net)
    return out


def fixture() -> dict:
    cases = []
    for d in (1.0, 3.0, 6.0, 10.0):
        for with_e in (True, False):
            net = braess_network(with_e)
            cases.append({"scenario": "braess", "with_e": with_e, "demand": d, "arms": solve_all(net, braess_demand(d))})
    for seed in (9000, 9003):
        inst = make_grid(GRID_N, seed)
        dref = reference_demand_ff(inst)
        for rho in (1.0, 2.0):
            dem = inst.demand(rho * dref)
            cases.append({"scenario": "grid", "seed": seed, "rho": rho, "arms": solve_all(inst.network, dem, mix_c=0.5)})
    return {
        "schema": "flow-demo-sandbox-fixture",
        "schema_version": "1.0.0",
        "label": "engine fixture for the browser port test (not a research result)",
        "solver": {"algorithm": "gradient-projection", "tol": TOL, "max_iter": MAX_ITER},
        "cases": cases,
    }


def render(obj: dict) -> str:
    return json.dumps(obj, indent=1, sort_keys=True, ensure_ascii=True) + "\n"


def main(argv: list[str]) -> int:
    outputs = {OUT_NETWORKS: render(networks()), OUT_FIXTURE: render(fixture())}
    if "--check" in argv:
        bad = [p for p, t in outputs.items() if not p.exists() or p.read_text() != t]
        print("sandbox export check:", "identical" if not bad else f"DIFFERS: {[str(p.relative_to(ROOT)) for p in bad]}")
        return 1 if bad else 0
    for p, t in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(t)
        print(f"wrote {p.relative_to(ROOT)} ({len(t)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
